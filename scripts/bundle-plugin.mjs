#!/usr/bin/env node
// Bundles the horde servers into self-contained files inside the Claude Code plugin, so the
// plugin runs from a plain clone of this repository: no npm install, no build step.
//
//   node scripts/bundle-plugin.mjs           write plugins/horde/servers/
//   node scripts/bundle-plugin.mjs --check   fail if the committed bundles are out of date
import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import { fileURLToPath } from "node:url"
import * as esbuild from "esbuild"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const out = path.join(root, "plugins", "horde", "servers")
const version = JSON.parse(fs.readFileSync(path.join(root, "plugins", "horde", ".claude-plugin", "plugin.json"), "utf8")).version

// Every bundle lands in the same directory: the board finds its worker CLI (cli.js) and
// opencode its private-server supervisor (supervisor.js) next to the running module.
const entries = {
  opencode: "packages/opencode/src/index.ts",
  supervisor: "packages/opencode/src/supervisor.ts",
  board: "packages/board/src/index.ts",
  cli: "packages/board/src/cli.ts",
  verify: "packages/verify/src/index.ts",
  context: "packages/context/src/index.ts",
}

async function bundle(dir) {
  fs.mkdirSync(dir, { recursive: true })
  await esbuild.build({
    entryPoints: Object.fromEntries(Object.entries(entries).map(([name, file]) => [name, path.join(root, file)])),
    outdir: dir,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    conditions: ["source"],
    define: { HORDE_VERSION: JSON.stringify(version) },
    // Bundled CommonJS dependencies still call require().
    banner: { js: 'import { createRequire as __hordeRequire } from "node:module"; const require = __hordeRequire(import.meta.url);' },
    minify: true,
    keepNames: true,
    legalComments: "none",
    logLevel: "warning",
  })
  fs.writeFileSync(
    path.join(dir, "package.json"),
    `${JSON.stringify({ type: "module", private: true, description: "Generated by scripts/bundle-plugin.mjs; do not edit." }, null, 2)}\n`,
  )
}

if (process.argv.includes("--check")) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "horde-bundle-"))
  await bundle(tmp)
  const stale = fs
    .readdirSync(tmp)
    .filter((f) => !fs.existsSync(path.join(out, f)) || !fs.readFileSync(path.join(out, f)).equals(fs.readFileSync(path.join(tmp, f))))
  fs.rmSync(tmp, { recursive: true, force: true })
  if (stale.length) {
    console.error(`plugins/horde/servers is out of date (${stale.join(", ")}): run npm run bundle and commit the result`)
    process.exit(1)
  }
  console.log("plugin bundles are up to date")
} else {
  fs.rmSync(out, { recursive: true, force: true })
  await bundle(out)
  for (const f of fs.readdirSync(out)) console.log(`${path.relative(root, path.join(out, f))}  ${(fs.statSync(path.join(out, f)).size / 1024).toFixed(0)} KB`)
}
